#!/usr/bin/env node
/*
 * Render carousels for Buffer.
 *
 *   node tools/render-posts.js                 # every posts/*.json
 *   node tools/render-posts.js posts/foo.json  # just one
 *
 * For each carousel it opens Post Studio in headless Chromium and writes to
 * site/p/<slug>/ (deployed with the site, so every file gets a public URL):
 *
 *   motion 0      01.png, 02.png, ...            still slides
 *   motion > 0    01.mp4, 02.mp4, ...            6-second loops (needs ffmpeg)
 *                 01.jpg, 02.jpg, ...            first frame, used as the video thumbnail
 *   thumb.jpg, card.jpg  small and large cover for the website
 *   buffer.json   caption + media URLs + alt text, ready for Buffer's create_post
 *
 * Slides designed elsewhere (Figma exports) skip the studio: list them in
 * "images" (paths from the repo root) with one "alt" line each, and they are
 * copied in as 01.png, 02.png, ... with the same thumb.jpg and buffer.json.
 *
 * Set SITE_URL to where site/ is deployed so the URLs in buffer.json are real:
 *   SITE_URL=https://designrunnerlab.com node tools/render-posts.js
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..");
const SITE_URL = (process.env.SITE_URL || "https://YOUR-SITE").replace(/\/$/, "");
const slugify = s => String(s || "post").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "post";
const b64 = dataUrl => Buffer.from(dataUrl.split(",")[1], "base64");

function hasFfmpeg() {
  try { execFileSync("ffmpeg", ["-version"], { stdio: "ignore" }); return true; } catch (e) { return false; }
}

/* site/p/posts.js: every post's name, date and cover, so the website can show
   "From the post" with a thumbnail people recognise from Instagram. */
function writeIndex() {
  const index = {};
  for (const f of fs.readdirSync(path.join(ROOT, "posts")).filter(f => f.endsWith(".json")).sort()) {
    const j = JSON.parse(fs.readFileSync(path.join(ROOT, "posts", f), "utf8"));
    const slug = j.slug || slugify(path.basename(f, ".json"));
    const dir = path.join(ROOT, "site", "p", slug);
    const cover = ["thumb.jpg", "01.jpg", "01.png"].find(c => fs.existsSync(path.join(dir, c)));
    const card = fs.existsSync(path.join(dir, "card.jpg")) ? `p/${slug}/card.jpg` : "";
    index[slug] = { name: j.name, date: j.date || "", purpose: j.purpose || "", cover: cover ? `p/${slug}/${cover}` : "", card };
  }
  fs.writeFileSync(path.join(ROOT, "site", "p", "posts.js"), "/* Generated by tools/render-posts.js */\nwindow.POSTS = " + JSON.stringify(index, null, 2) + ";\n");
}

async function main() {
  const args = process.argv.slice(2);
  const files = args.length
    ? args.map(f => path.resolve(f))
    : fs.readdirSync(path.join(ROOT, "posts")).filter(f => f.endsWith(".json")).map(f => path.join(ROOT, "posts", f));
  if (!files.length) { console.log("No posts/*.json found."); return; }

  const launch = process.env.HTTPS_PROXY ? { proxy: { server: process.env.HTTPS_PROXY } } : {};
  const browser = await chromium.launch(launch);
  const page = await browser.newPage();
  page.on("pageerror", e => console.error("  studio error:", e.message));
  await page.goto("file://" + path.join(ROOT, "studio", "index.html"));
  await page.waitForFunction(() => window.PostStudio);
  const ffmpeg = hasFfmpeg();

  for (const file of files) {
    const json = JSON.parse(fs.readFileSync(file, "utf8"));
    const slug = json.slug || slugify(path.basename(file, ".json"));
    const outDir = path.join(ROOT, "site", "p", slug);
    fs.mkdirSync(outDir, { recursive: true });
    for (const f of fs.readdirSync(outDir)) if (/\.(png|jpg|mp4)$/.test(f)) fs.unlinkSync(path.join(outDir, f));

    const stills = json.images
      ? json.images.map((f, i) => ({ n: i + 1, file: path.join(ROOT, f),
          png: "data:image/png;base64," + fs.readFileSync(path.join(ROOT, f)).toString("base64"),
          alt: `Slide ${i + 1} of ${json.images.length}. ${(json.alt || [])[i] || ""}`.trim() }))
      : await page.evaluate(j => window.PostStudio.render(j), json);
    // small cover thumbnail for the website's Links page
    const thumb = await page.evaluate(src => new Promise(res => {
      const im = new Image();
      im.onload = () => { const c = document.createElement("canvas"); c.width = 240; c.height = 300;
        const x = c.getContext("2d"); x.imageSmoothingQuality = "high"; x.drawImage(im, 0, 0, 240, 300); res(c.toDataURL("image/jpeg", 0.8)); };
      im.src = src;
    }), stills[0].png);
    fs.writeFileSync(path.join(outDir, "thumb.jpg"), b64(thumb));
    // larger cover for the Read gallery cards
    const card = await page.evaluate(src => new Promise(res => {
      const im = new Image();
      im.onload = () => { const c = document.createElement("canvas"); c.width = 640; c.height = 800;
        const x = c.getContext("2d"); x.imageSmoothingQuality = "high"; x.drawImage(im, 0, 0, 640, 800); res(c.toDataURL("image/jpeg", 0.85)); };
      im.src = src;
    }), stills[0].png);
    fs.writeFileSync(path.join(outDir, "card.jpg"), b64(card));
    const motion = Number(json.motion) || 0;
    let media;

    if (json.images) {
      media = stills.map(s => {
        const name = String(s.n).padStart(2, "0") + ".png";
        fs.copyFileSync(s.file, path.join(outDir, name));
        return { type: "image", file: `p/${slug}/${name}`, url: `${SITE_URL}/p/${slug}/${name}`, alt: s.alt };
      });
    } else if (motion > 0 && !ffmpeg) console.warn(`  ${slug}: motion is ${motion * 100}% but ffmpeg isn't installed, so slides stay still.`);
    else if (motion > 0 && ffmpeg) {
      const info = await page.evaluate(j => window.PostStudio.prepare(j), json);
      const frames = Math.round(info.loop * info.fps);
      media = [];
      for (let i = 0; i < info.slides; i++) {
        const name = String(i + 1).padStart(2, "0");
        const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "drl-frames-"));
        for (let f = 0; f < frames; f++) {
          const url = await page.evaluate(([i, t]) => window.PostStudio.frame(i, t), [i, f / info.fps]);
          fs.writeFileSync(path.join(tmp, String(f).padStart(4, "0") + ".jpg"), b64(url));
        }
        fs.copyFileSync(path.join(tmp, "0000.jpg"), path.join(outDir, name + ".jpg"));
        // H.264 + yuv420p + faststart: the format Instagram expects
        execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-framerate", String(info.fps), "-i", path.join(tmp, "%04d.jpg"),
          "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "slow", "-movflags", "+faststart",
          path.join(outDir, name + ".mp4")]);
        fs.rmSync(tmp, { recursive: true, force: true });
        media.push({ type: "video", file: `p/${slug}/${name}.mp4`, url: `${SITE_URL}/p/${slug}/${name}.mp4`,
          thumbnail: `${SITE_URL}/p/${slug}/${name}.jpg`, alt: stills[i].alt });
        process.stdout.write(`\r  ${slug}: slide ${i + 1}/${info.slides} encoded`);
      }
      process.stdout.write("\n");
    } else {
      media = stills.map(s => {
        const name = String(s.n).padStart(2, "0") + ".png";
        fs.writeFileSync(path.join(outDir, name), b64(s.png));
        return { type: "image", file: `p/${slug}/${name}`, url: `${SITE_URL}/p/${slug}/${name}`, alt: s.alt };
      });
    }

    const buffer = { slug, name: json.name, purpose: json.purpose, motion, caption: json.caption || "", media };
    fs.writeFileSync(path.join(outDir, "buffer.json"), JSON.stringify(buffer, null, 2) + "\n");
    console.log(`✓ ${slug}: ${media.length} ${media[0].type === "video" ? "videos" : "slides"} at ${Math.round(motion * 100)}% motion -> site/p/${slug}/`);
  }
  await browser.close();
  writeIndex();
  if (SITE_URL.includes("YOUR-SITE")) console.log("\nSet SITE_URL to your deployed site so buffer.json has real media URLs.");
}

main().catch(err => { console.error(err); process.exit(1); });
